#!/usr/bin/env python3
"""Preserve only authenticated 100-frame original S09E19 visual evidence.

No image semantic labels or continuous-motion conclusions are generated by
this importer. Reviewers must inspect original image sequence first.
"""
from __future__ import annotations
import hashlib,json,shutil,sys
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
TARGET=ROOT/"seasons"/"S09"/"S09E19"/"derived"/"visual-review-v1"
SOURCE_SHA="51f409c620245f9f3744b1b38e534122fd8c82cfadc2221bf5f6fc14eac93649"
TXT_SHA="659beb9c50fabdd1028aac9570999d9a16b36e6d582938e10809cc0c664530b2"
SOURCE_ANCHORS=ROOT/"seasons"/"S09"/"S09E19"/"derived"/"source-timing-review-v1"/"sparse-source-paragraph-candidates.json"

def sha(path):
    h=hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda:f.read(1024*1024),b""):h.update(block)
    return h.hexdigest()

def validate(source):
    if not source.is_dir():raise ValueError("No source image folder")
    report=json.loads((source/"frame-source-index.json").read_text("utf-8"))
    if not (report.get("schema")=="night-court-s09e19-video-frame-samples/1"
        and report.get("episode_id")=="S09E19"
        and report.get("source_original_avi_sha256")==SOURCE_SHA
        and report.get("original_untimed_text_sha256")==TXT_SHA
        and report.get("source_window_ms")==[900000,925000]
        and report.get("nominal_sampling_hz")==4
        and report.get("sample_count")==100
        and report.get("source_paragraph_timecode_verified") is False
        and report.get("scene_setting_reviewed") is False
        and report.get("physical_action_continuous_video_reviewed") is False
        and report.get("character_speaker_identified") is False
        and report.get("original_video_or_audio_in_artifact") is False
        and report.get("episode_audiovisual_complete") is False):
        raise ValueError("Unrecognized original or overstated video/frame evidence")
    images=report.get("frames",[])
    if len(images)!=100 or len(set(x["file"] for x in images))!=100:
        raise ValueError("Frame loss or duplicate source references")
    expected={"frame-source-index.json","contact-sheet.jpg"} | {x["file"] for x in images}
    actual={str(p.relative_to(source)) for p in source.rglob("*") if p.is_file()}
    if actual!=expected:raise ValueError("Unknown media or unapproved extra artifact files")
    for idx,x in enumerate(images):
        if (x["file"]!=f"frames/frame-{idx+1:03d}.jpg" or x["sample_index"]!=idx+1
            or x["approx_source_time_ms"]!=900000+250*idx
            or x["reviewed_for_scene_content"] or x["motion_interpolation_verified"]):
            raise ValueError("Original image order, timestamp or epistemic flag changed")
        image=source/x["file"]
        if image.stat().st_size>150_000 or sha(image)!=x["sha256"]:
            raise ValueError("Source AVI JPEG hash changed or oversized")
    if sha(source/"contact-sheet.jpg")!=report["contact_sheet_sha256"]:
        raise ValueError("Source montage checksum changed")
    if sum(p.stat().st_size for p in source.rglob("*") if p.is_file())>12_000_000:
        raise ValueError("Visual research artifact exceeds approved size")
    anchors=json.loads(SOURCE_ANCHORS.read_text("utf-8"))
    if (anchors["source_video_sha256"]!=SOURCE_SHA
        or anchors["original_untimed_transcript_sha256"]!=TXT_SHA
        or anchors["distinct_high_lexical_match_candidates_total"]!=15):
        raise ValueError("Cross-modal original media and source text identity mismatch")
    selected=[x for x in anchors["windows"] if x["source_window_ms"]==[900000,925000]]
    if len(selected)!=1 or selected[0]["distinct_high_lexical_match_candidates"]!=5:
        raise ValueError("Wrong visual window/source text comparison")
    return report,selected[0]

def import_packet(path):
    if TARGET.exists():raise ValueError("Prior episode visual review must not be overwritten")
    report,matched=validate(path)
    TARGET.mkdir(parents=True)
    shutil.copy2(path/"frame-source-index.json",TARGET/"frame-source-index.json")
    shutil.copy2(path/"contact-sheet.jpg",TARGET/"contact-sheet.jpg")
    shutil.copytree(path/"frames",TARGET/"frames")
    provenance={
       "schema":"night-court-s09e19-visual-review-evidence/1",
       "episode_id":"S09E19",
       "source_media_sha256":SOURCE_SHA,"original_untimed_text_sha256":TXT_SHA,
       "nominal_source_window_ms":[900000,925000],"frames_hash_verified":100,
       "related_source_paragraph_candidates":[x["source_paragraph_candidate"]
          for x in matched["text_alignment_candidates"] if x["source_paragraph_candidate"]],
       "scene_observations":[],
       "editorial_review_status":"frames_collected_not_yet_visually_interpreted",
       "voice_and_character_identities_verified":False,
       "sampled_motion_continuity_verified":False,
       "actual_source_utterance_timecodes_verified":False,
       "source_episode_audiovisual_complete":False,
       "source_sampled_film_republished":False
    }
    (TARGET/"visual-source-review.json").write_text(json.dumps(provenance,indent=2)+"\n","utf-8")
    (TARGET/"README.md").write_text(
        "# S09E19 actual video source scene frames\n\n"
        "100 original-video sampled images, nominal 4fps from 15:00–15:25, SHA verified.\n\n"
        "The sampled frames and contact sheet are unreviewed source evidence.\n"
        "Their presence does not prove an actor's name, scene location, action,\n"
        "dialogue-to-mouth correspondence or continuous motion. Review the JSON index.\n"
        "The five related untimed-source lexical paragraph candidates are only\n"
        "potential links; no original paragraph has been assigned a timestamp.\n",
        "utf-8")
    print("S09E19 preserved 100 SHA-verified visual source frames, five original-text candidate locators; no invented scene description.")

if __name__=="__main__":
    if len(sys.argv)!=2:raise SystemExit("usage: import_s09e19_visual_review.py EXTRACTED_ARTIFACT_FOLDER")
    import_packet(Path(sys.argv[1]))
